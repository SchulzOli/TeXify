"""Generate THIRD_PARTY.md: every open-source component TeXify builds on.

Sources of truth (nothing is maintained by hand):
  * Python dependencies  -> pyproject.toml (+ installed metadata for version/license)
  * LaTeX packages       -> \\documentclass / \\usepackage / \\RequirePackage in all templates
  * System components    -> Dockerfile (apt packages, base image)

Usage:  python scripts/third_party.py           (write THIRD_PARTY.md)
        python scripts/third_party.py --check   (exit 1 if the file is outdated, for CI)
"""

from __future__ import annotations

import re
import sys
import tomllib
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "THIRD_PARTY.md"
TEMPLATES = ROOT / "texify" / "templates"
OWN = {"texify", "texify-letter"}


def python_deps() -> list[tuple[str, str, str, str]]:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    groups = {"core": project["dependencies"]}
    for extra, deps in project.get("optional-dependencies", {}).items():
        groups[extra] = [d for d in deps if not d.startswith("texify")]
    rows = []
    for group, deps in groups.items():
        for spec in deps:
            name = re.split(r"[<>=!~\[ ]", spec, maxsplit=1)[0]
            try:
                meta = metadata.metadata(name)
                lic = meta.get("License-Expression") or (meta.get("License") or "").split("\n")[0]
                if not lic or len(lic) > 40:
                    lic = next((c.split("::")[-1].strip() for c in meta.get_all("Classifier") or []
                                if c.startswith("License ::")), lic[:40] or "?")
            except metadata.PackageNotFoundError:
                lic = "?"
            rows.append((name, group, lic, f"https://pypi.org/project/{name}/"))
    return rows


def latex_packages() -> dict[str, set[str]]:
    used: dict[str, set[str]] = {}
    pattern = re.compile(r"\\(?:usepackage|RequirePackage|documentclass)(?:\[[^\]]*\])?\{([^}]+)\}")
    for f in sorted(TEMPLATES.rglob("*")):
        if f.suffix not in {".tex", ".sty"}:
            continue
        for m in pattern.finditer(f.read_text(encoding="utf-8")):
            for pkg in m.group(1).split(","):
                pkg = pkg.strip()
                if pkg and pkg not in OWN and "\\" not in pkg:
                    used.setdefault(pkg, set()).add(f.parent.name)
    return used


def system_components() -> list[str]:
    text = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    base = re.search(r"^FROM\s+(\S+)", text, re.M).group(1)
    apt = re.search(r"apt-get install[^\n]*\n(.*?)&&", text, re.S).group(1)
    pkgs = [p for p in re.findall(r"^\s+([a-z0-9][a-z0-9.+-]+)\s*\\?$", apt, re.M)]
    return [f"Docker base image `{base}`"] + [f"Debian package `{p}`" for p in pkgs]


def render() -> str:
    lines = [
        "# Third-party components",
        "",
        "Generated by `scripts/third_party.py` – do not edit by hand.",
        "Sources: `pyproject.toml`, all templates (`\\usepackage`), `Dockerfile`.",
        "",
        "## Python",
        "",
        "| Package | Group | License | Project |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n} | {g} | {lic} | {url} |" for n, g, lic, url in python_deps()]
    lines += [
        "",
        "## LaTeX packages (TeX Live / CTAN)",
        "",
        "| Package | used in |",
        "|---|---|",
    ]
    lines += [f"| [{p}](https://ctan.org/pkg/{p}) | {', '.join(sorted(w))} |"
              for p, w in sorted(latex_packages().items())]
    lines += ["", "## System", ""]
    lines += [f"- {c}" for c in system_components()]
    lines += ["- LaTeX engines (optional, local): Tectonic, TeX Live, MiKTeX", ""]
    return "\n".join(lines)


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print("THIRD_PARTY.md is outdated: python scripts/third_party.py")
            return 1
        return 0
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"{OUT.name} written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
